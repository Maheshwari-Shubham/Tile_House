// Get sorted state names
export const STATE_NAMES = Object.keys(INDIA_STATES_DISTRICTS).sort();

// Get districts for a state
export function getDistricts(stateName) {
  return INDIA_STATES_DISTRICTS[stateName]?.districts || [];
}

// Get lat/lng for a district
export function getDistrictCoords(stateName, districtName) {
  const districts = getDistricts(stateName);
  return districts.find(d => d.name === districtName) || null;
}
